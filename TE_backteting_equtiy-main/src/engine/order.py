"""
order.py

Explicit Order abstraction for the QUANTLAB Backtesting Engine.
Separates trading signals from order creation and execution.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional
import uuid
import pandas as pd


class OrderSide(str, Enum):
    BUY = "BUY"
    SELL = "SELL"


class OrderType(str, Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"  # Extensible for future limit order support


class OrderStatus(str, Enum):
    PENDING = "PENDING"
    FILLED = "FILLED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"


@dataclass
class Order:
    """
    Represents an order generated by the strategy and position sizer.

    Attributes
    ----------
    timestamp : pd.Timestamp
        Timestamp when signal/order was created.
    symbol : str
        Ticker symbol.
    side : OrderSide
        BUY or SELL.
    quantity : int
        Number of shares to trade.
    order_type : OrderType
        MARKET (extensible to LIMIT).
    reference_price : float
        Price of reference bar when order was generated.
    order_id : str
        Unique identifier.
    status : OrderStatus
        Current lifecycle status.
    signal_bar_idx : int
        Index of the bar where signal occurred.
    reason : str
        Reason for order (e.g. 'Signal BUY', 'Stop Loss', 'Take Profit').
    """
    timestamp: pd.Timestamp
    symbol: str
    side: OrderSide
    quantity: int
    order_type: OrderType = OrderType.MARKET
    reference_price: float = 0.0
    order_id: str = field(default_factory=lambda: f"ORD-{uuid.uuid4().hex[:8].upper()}")
    status: OrderStatus = OrderStatus.PENDING
    signal_bar_idx: int = -1
    reason: str = "Signal"

    def is_buy(self) -> bool:
        return self.side == OrderSide.BUY

    def is_sell(self) -> bool:
        return self.side == OrderSide.SELL

    def to_dict(self) -> dict:
        return {
            "order_id": self.order_id,
            "timestamp": str(self.timestamp),
            "symbol": self.symbol,
            "side": str(self.side),
            "quantity": self.quantity,
            "order_type": str(self.order_type),
            "reference_price": self.reference_price,
            "status": str(self.status),
            "reason": self.reason
        }
